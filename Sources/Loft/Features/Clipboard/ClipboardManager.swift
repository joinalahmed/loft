import AppKit
import SwiftUI
import Combine
import UniformTypeIdentifiers

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, url, image, files, color }
    let id: UUID
    var kind: Kind
    var text: String          // text / url / file paths joined by \n / image filename
    var date: Date
    var pinned = false
    var sourceBundle: String?

    var preview: String {
        switch kind {
        case .image: return "Image"
        case .files: return text.components(separatedBy: "\n").map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        default: return text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        }
    }
    var symbol: String {
        switch kind {
        case .text: "text.alignleft"
        case .url: "link"
        case .image: "photo"
        case .files: "doc"
        case .color: "paintpalette"
        }
    }
}

@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()
    @Published private(set) var items: [ClipItem] = []
    @Published var query = ""
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var suppressNext = false
    private let prefs = Preferences.shared
    private let dir = AppSupport.directory("Clipboard")

    private init() { load() }

    var filtered: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        let base = q.isEmpty ? items : items.filter { $0.text.lowercased().contains(q) || $0.kind.rawValue.contains(q) }
        return base.sorted { ($0.pinned ? 1 : 0, $0.date) > ($1.pinned ? 1 : 0, $1.date) }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard prefs.clipboardEnabled else { return }
        if suppressNext { suppressNext = false; return }
        let types = pb.types ?? []
        // Respect password managers and transient pasteboards.
        if types.contains(where: { $0.rawValue == "org.nspasteboard.ConcealedType" || $0.rawValue == "org.nspasteboard.TransientType" || $0.rawValue == "org.nspasteboard.AutoGeneratedType" }) { return }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(ClipItem(id: UUID(), kind: .files, text: urls.map(\.path).joined(separator: "\n"), date: Date(), sourceBundle: source))
        } else if let s = pb.string(forType: .string), !s.isEmpty {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            var kind: ClipItem.Kind = .text
            if let u = URL(string: trimmed), let scheme = u.scheme, ["http", "https"].contains(scheme), !trimmed.contains(" ") { kind = .url }
            else if trimmed.range(of: "^#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})$", options: .regularExpression) != nil { kind = .color }
            add(ClipItem(id: UUID(), kind: kind, text: String(s.prefix(20_000)), date: Date(), sourceBundle: source))
        } else if let img = NSImage(pasteboard: pb) {
            let name = UUID().uuidString + ".png"
            if let tiff = img.resized(maxDimension: 1600).tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
               let png = rep.representation(using: .png, properties: [:]) {
                try? png.write(to: dir.appendingPathComponent(name))
                add(ClipItem(id: UUID(), kind: .image, text: name, date: Date(), sourceBundle: source))
            }
        }
    }

    private func add(_ item: ClipItem) {
        if let i = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text }) {
            var existing = items.remove(at: i)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        let limit = max(10, prefs.clipboardLimit)
        let unpinned = items.filter { !$0.pinned }
        if unpinned.count > limit {
            let drop = Set(unpinned.suffix(unpinned.count - limit).map(\.id))
            for item in items where drop.contains(item.id) && item.kind == .image {
                try? FileManager.default.removeItem(at: dir.appendingPathComponent(item.text))
            }
            items.removeAll { drop.contains($0.id) }
        }
    }

    func image(for item: ClipItem) -> NSImage? {
        guard item.kind == .image else { return nil }
        return NSImage(contentsOf: dir.appendingPathComponent(item.text))
    }

    // MARK: Actions

    func copy(_ item: ClipItem, plain: Bool = false) {
        let pb = NSPasteboard.general
        suppressNext = true
        pb.clearContents()
        switch item.kind {
        case .files:
            let urls = item.text.components(separatedBy: "\n").map { URL(fileURLWithPath: $0) as NSURL }
            pb.writeObjects(urls)
        case .image:
            if let img = image(for: item) { pb.writeObjects([img]) }
        default:
            pb.setString(item.text, forType: .string)
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(of: item) { items[i].date = Date() }
        save()
        NotchViewModel.shared.show(message: IslandMessage(title: "Copied", subtitle: item.preview, symbol: "doc.on.clipboard.fill", tint: .cyan), duration: 1.5)
    }

    /// Copies and then simulates ⌘V in the frontmost app (needs Accessibility).
    func paste(_ item: ClipItem) {
        copy(item)
        NotchViewModel.shared.close()
        guard AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
            down?.flags = .maskCommand; up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap); up?.post(tap: .cghidEventTap)
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle(); save()
    }

    func delete(_ item: ClipItem) {
        if item.kind == .image { try? FileManager.default.removeItem(at: dir.appendingPathComponent(item.text)) }
        items.removeAll { $0.id == item.id }; save()
    }

    func clear(keepPinned: Bool = true) {
        for item in items where (!keepPinned || !item.pinned) && item.kind == .image {
            try? FileManager.default.removeItem(at: dir.appendingPathComponent(item.text))
        }
        items.removeAll { !keepPinned || !$0.pinned }; save()
    }

    // MARK: Persistence

    private var file: URL { dir.appendingPathComponent("history.json") }

    private func load() {
        guard let data = try? Data(contentsOf: file),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    func injectDemo(_ demo: [ClipItem]) { items = demo }

    private func save() {
        guard !Demo.active else { return }
        if let data = try? JSONEncoder().encode(items) { try? data.write(to: file, options: .atomic) }
    }
}

enum AppSupport {
    static func directory(_ name: String) -> URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Loft", isDirectory: true).appendingPathComponent(name, isDirectory: true)
        try? FileManager.default.createDirectory(at: base, withIntermediateDirectories: true)
        return base
    }
}
